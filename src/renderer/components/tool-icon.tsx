export function iconComponent(name: unknown): LucideIcon {
  return ICONS[isToolIconName(name) ? name : DEFAULT_TOOL_ICON]
}

export function ToolIcon({ name, className }: { name: unknown; className?: string }) {
  const Icon = iconComponent(name)
  return <Icon className={cn('size-4', className)} aria-hidden="true" />
}
